"""Identify the numerical implementation and the physical GPU for new ring stage checkpoints."""
import ctypes
import hashlib
import importlib.metadata as metadata
import json
import os
from pathlib import Path
import platform
import shutil
import subprocess
import sys

# This list is also the installed/exported numerical worker's local dependency closure.
RING_SOURCE_FILES = (
    'scripts/calibrate_loaded_ring3d.py',
    'scripts/calibrate_ring.py',
    'scripts/gpu_timing.py',
    'scripts/ring_wall_tensor.py',
    'scripts/measure_loaded_ring_losses.py',
    'scripts/calibration_checkpoint.py',
    'scripts/ring_stage_provenance.py',
    'backend/__init__.py',
    'backend/adapters/fdtdx_adapter.py',
    'backend/adapters/fdtdx3d_adapter.py',
    'backend/adapters/fdtdx_ports_adapter.py',
    'backend/adapters/fdtdx_ports3d_adapter.py',
)

SCHEMA = 'fdtdx-loaded-ring-stage-v2'


def digest_file(path):
    with Path(path).open('rb') as stream:
        return hashlib.file_digest(stream, 'sha256').hexdigest()


def json_digest(value):
    return hashlib.sha256(json.dumps(value, sort_keys=True, separators=(',', ':')).encode()).hexdigest()


def source_fingerprint(root):
    return {name: digest_file(root / name) for name in RING_SOURCE_FILES}


def software_fingerprint():
    """Hash the installed numerical distributions and active transitive dependencies.

    RECORD metadata alone cannot detect a patched module under the same installed version.
    Read the actual wheel payload, including native libraries, compiler inputs and Python files.
    Absolute install paths, executable entry-point wrappers and generated bytecode are excluded.
    """
    from packaging.requirements import Requirement
    from packaging.utils import canonicalize_name

    available = {canonicalize_name(d.metadata['Name']): d for d in metadata.distributions()
                 if d.metadata.get('Name')}
    pending = {'fdtdx', 'jax', 'jaxlib', 'numpy', 'scipy', 'tidy3d'}
    pending.update(k for k in available if k.startswith(('nvidia-', 'jax-cuda')))
    distributions = {}
    while pending:
        name = pending.pop()
        if name in distributions:
            continue
        dist = available[name]
        origin = json.loads(dist.read_text('direct_url.json') or '{}')
        if origin.get('dir_info', {}).get('editable'):
            raise ValueError(f'Editable numerical distribution has external mutable code: {name}')
        if not dist.files:
            raise ValueError(f'Installed numerical distribution {name} has no file manifest.')
        hashes = {}
        for entry in dist.files:
            relative = Path(str(entry))
            if relative.is_absolute() or '..' in relative.parts or relative.suffix == '.pyc':
                continue
            if any(part.endswith('.dist-info') for part in relative.parts):
                continue
            path = dist.locate_file(entry)
            if not path.is_file():
                raise ValueError(f'Numerical distribution file is missing: {name}/{relative.as_posix()}')
            hashes[relative.as_posix()] = digest_file(path)
        if not hashes:
            raise ValueError(f'Numerical distribution {name} has no verifiable runtime files.')
        metadata_hash = json_digest({filename: dist.read_text(filename) for filename in
                                    ('METADATA', 'WHEEL', 'entry_points.txt')})
        distributions[name] = {'version': dist.version, 'files': len(hashes), 'sha256': json_digest(hashes),
                               'distribution_metadata_sha256': metadata_hash}
        for declaration in dist.requires or ():
            requirement = Requirement(declaration)
            if requirement.marker is None or requirement.marker.evaluate({'extra': ''}):
                pending.add(canonicalize_name(requirement.name))
    return dict(sorted(distributions.items()))


def physical_gpu(target):
    """Resolve the JAX local CUDA ordinal to a driver UUID without publishing the identifier."""
    if target.platform != 'gpu':
        raise ValueError('A CUDA field device is required.')
    ordinal = int(target.local_hardware_id)
    driver = ctypes.CDLL('libcuda.so.1')
    def call(function, *args):
        status = getattr(driver, function)(*args)
        if status:
            raise ValueError(f'{function} returned CUDA error {status}.')

    call('cuInit', 0)
    handle = ctypes.c_int()
    call('cuDeviceGet', ctypes.byref(handle), ordinal)
    uuid = (ctypes.c_ubyte * 16)()
    # CUDA12 worker profiles support the MIG-aware v2 identity.
    call('cuDeviceGetUuid_v2', ctypes.byref(uuid), handle)
    label = ctypes.create_string_buffer(256)
    call('cuDeviceGetName', label, len(label), handle)
    if label.value.decode() != target.device_kind or not any(uuid):
        raise ValueError('CUDA driver and local JAX GPU identity differ.')
    api = ctypes.c_int()
    call('cuDriverGetVersion', ctypes.byref(api))
    # Driver build is host-global. No host path, card UUID or PCI address is retained in public data.
    smi = shutil.which('nvidia-smi') or '/usr/lib/wsl/lib/nvidia-smi'
    versions = subprocess.run([smi, '--query-gpu=driver_version', '--format=csv,noheader,nounits'],
                              capture_output=True, text=True, timeout=5, check=True).stdout.splitlines()
    versions = set(v.strip() for v in versions if v.strip())
    if len(versions) != 1:
        raise ValueError('Cannot identify a unique active GPU driver build.')
    return {'model': target.device_kind, 'cuda_ordinal': ordinal, 'logical_device': str(target),
            'driver_build': versions.pop(), 'cuda_driver_api': api.value,
            'private_device_key': hashlib.sha256(b'photonics-workbench:gpu-v2\0' + bytes(uuid)).hexdigest()}


def fingerprint(root, runtime, versions):
    jax, _, _, target = runtime
    flags = {key: os.environ.get(key) for key in ('XLA_FLAGS', 'CUDA_VISIBLE_DEVICES', 'JAX_CUDA_VISIBLE_DEVICES',
            'NVIDIA_TF32_OVERRIDE', 'TF_CUDNN_DETERMINISTIC', 'CUBLAS_WORKSPACE_CONFIG', 'JAX_PJRT_CLIENT_CREATE_OPTIONS',
            'OPENBLAS_NUM_THREADS', 'OPENBLAS_CORETYPE', 'OMP_NUM_THREADS', 'MKL_NUM_THREADS',
            'PHOTONICS_CUPTI', 'XLA_PYTHON_CLIENT_PREALLOCATE', 'XLA_PYTHON_CLIENT_ALLOCATOR')}
    record = {'schema': SCHEMA, 'source_files': source_fingerprint(root), 'versions': versions,
              'backend_flags_sha256': json_digest(flags), 'python_abi': sys.implementation.cache_tag,
              'python': sys.version.split()[0], 'architecture': platform.machine(),
              'jax_configuration': {key: str(getattr(jax.config, key)) for key in
                                    ('jax_enable_x64', 'jax_default_matmul_precision', 'jax_disable_jit')}}
    try:
        record['hardware'] = physical_gpu(target)
        record['installed_numerics'] = software_fingerprint()
    except (AttributeError, ImportError, OSError, TypeError, ValueError, KeyError, subprocess.SubprocessError) as error:
        # Fresh simulation is still available on the explicitly verified CUDA target.
        # Its anonymous temporary directory cannot share stages between workers or different GPUs.
        record['reuse_disabled_reason'] = 'Numerical environment or physical GPU could not be verified (' + type(error).__name__ + ').'
        return record, False
    return record, True


def public_fingerprint(private):
    public = dict(private)
    if 'hardware' in public:
        public['hardware'] = {key: value for key, value in public['hardware'].items() if key != 'private_device_key'}
    return public
